/**
 * 「能选」的取值 —— 枚举 ∪ 用户自己加过的（本机清单）。**编辑/新建用的下拉就是这一份**。
 *
 * 这里刻意**不扫记录**：写进记录里的值不该反过来变成下拉里的一个选项。
 * 从前扫了，于是删掉一个自定义取值后它还在选项里（那条记录还在用它），
 * 用户看到的和"删掉"这句话对不上 —— 删除功能因此形同虚设。
 * 「这条记录自己的旧值」由编辑弹窗单独补一个选项（见 dashboard.js 的 fillTypeEditors），
 * 免得一打开旧记录就被迫改回枚举值；筛选用的是下面那份带记录的 typeValues。
 */
export function typeChoices(field, data) {
  const enums = field === 'nature' ? NATURE_LIST : INDUSTRY_LIST;
  const seen = new Set(enums);
  const out = [...enums];
  for (const v of data?.customTypes?.[field] || []) {
    const t = String(v == null ? '' : v).trim();
    if (t && !seen.has(t)) { seen.add(t); out.push(t); }
  }
  return out;
}

/**
 * 筛选下拉的取值 —— 枚举 ∪ 本机自定义值 ∪ **记录里实际出现过的值**。
 * 最后一类只有筛选用得上：筛选要能筛到"库里有、但枚举里没有"的写法，
 * 哪怕它是别的设备填的、本机清单里根本没有。
 */
export function typeValues(field, data) {
  const seen = new Set();
  const out = [];
  const pushAll = (list) => {
    for (const v of list) {
      const t = String(v == null ? '' : v).trim();
      if (t && !seen.has(t)) { seen.add(t); out.push(t); }
    }
  };
  pushAll(typeChoices(field, data));
  for (const rec of data?.records || []) pushAll([rec?.[field]]);
  return out;
}

// ---------------------------------------------------------------------------
// 自定义取值清单：用户自己划的分类（data.customTypes）
//
// 它有两个用处，**必须同源**：
//   ① 下拉里能选到什么（typeChoices 已经把 customTypes 收进去了）
//   ② **问模型时能答出什么**：这份清单随请求一起发上去、进提示词，白名单也跟着放宽 ——
//      否则"用户加了「银行」"只是多了个能选的选项，模型那头永远给不出它（等于白加）。
// 收敛规则在两个地方各有一份实现（这里一份、服务端 core.js 一份）：客户端这份决定发什么，
// 服务端那份不信任客户端，收到什么都要重收敛一遍。
// ---------------------------------------------------------------------------
export const CUSTOM_OPT = '__custom__';   // 下拉里「＋ 自定义…」那一项的值（不是合法取值）
export const CUSTOM_MAX_ITEMS = 40;       // 每栏最多留 40 项（与 rememberCustomType 同一个数）
export const CUSTOM_MAX_LEN = 20;         // 单个取值最长 20 字（与面板那个输入框同一个口径）

/**
 * 本机清单的**收敛形态**：`{nature:[], industry:[]}`（永远返回对象，不返回 null）。
 * 去空、去枚举值（枚举本来就在候选集里，重名的不必再说一遍）、去重、逐项截断。
 * 顺序＝用户添加的顺序（后加的在后），`customSig` 直接拿它做指纹。
 */
export function customTypesOf(data) {
  const out = { nature: [], industry: [] };
  for (const field of ['nature', 'industry']) {
    const enums = field === 'nature' ? NATURE_LIST : INDUSTRY_LIST;
    const seen = new Set();
    for (const raw of data?.customTypes?.[field] || []) {
      const v = String(raw == null ? '' : raw).trim().slice(0, CUSTOM_MAX_LEN);
      if (!v || enums.indexOf(v) >= 0 || seen.has(v)) continue;
      if (/[:：]/.test(v)) continue;   // 提示词里用「：」分行，放任它等于让人伪造一行
      seen.add(v);
      out[field].push(v);
    }
    out[field] = out[field].slice(-CUSTOM_MAX_ITEMS);
  }
  return out;
}

/** 要发给服务端的那一份；两栏都空时返回 null（空清单不发这个字段，请求体与以前逐字节一致）。 */
export function customPayload(data) {
  const c = customTypesOf(data);
  return (c.nature.length || c.industry.length) ? c : null;
}

/**
 * 清单指纹（企业类型缓存用）：清单一变，缓存里那些按旧候选集问出来的答案就不该再用了。
 * 空清单是空串 —— 老缓存行没有这个字段，读作空串正好命中，没有自定义值的人零影响。
 */
export function customSig(data) {
  const c = customPayload(data);
  return c ? JSON.stringify([c.nature, c.industry]) : '';
}

/** 这一次允许的取值 = 枚举 ∪ 自定义（服务端与客户端都用这个口径判定，别各写一份）。 */
export function allowedTypes(field, custom) {
  const enums = field === 'nature' ? NATURE_LIST : INDUSTRY_LIST;
  const extra = custom?.[field];
  if (!Array.isArray(extra) || !extra.length) return enums;
  const seen = new Set(enums);
  const out = [...enums];
  for (const raw of extra) {
    const v = String(raw == null ? '' : raw).trim();
    if (v && !seen.has(v)) { seen.add(v); out.push(v); }
  }
  return out;
}

/**
 * 候选值比对用的"写法归一"：抹掉空白与分隔符/句读（/ \ 、 ， 。 等），再小写。
 * 服务端 core.js 的 typeNorm 是同一套规则（tools/test-ai.mjs 断言两边一致）。
 *
 * 它只抹**写法**，绝不做语义猜测 —— 不做包含/前缀匹配，所以「非金融」不会对上「金融」。
 * 存在的理由：模型把同一个值写成带空格/全角/顿号的变体是常事，逐字比对会把正确答案
 * 一起丢掉，用户看到的就是"AI 什么都没认出来"。
 */
const TYPE_NORM_DROP = /[\s　/\\／＼、，,。.．·・|｜;；:："'“”‘’「」『』()（）\[\]【】\-—_－＿～〜]/g;
export function typeNorm(v) {
  return String(v == null ? '' : v).replace(/[\u0000-\u001f\u007f]+/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 60)
    .replace(TYPE_NORM_DROP, '').toLowerCase();
}

/** 是不是枚举值（**逐字**，不带写法容错）—— 判断"要不要记成自定义值"用的就是它。 */
export function isEnumType(field, v) {
  const enums = field === 'nature' ? NATURE_LIST : INDUSTRY_LIST;
  return enums.indexOf(String(v == null ? '' : v).trim()) >= 0;
}

/**
 * 这个值这次允不允许（枚举里的算允许、本次清单里的也算）。
 * 判据与**服务端解析模型答案时**用的是同一套：先逐字，再按 typeNorm 归一唯一命中，
 * 归一后撞上"枚举 vs 自定义"时以自定义为准（两个自定义撞一起就没法二选一，不算允许）。
 * 两边必须一致：服务端收了、客户端又把它当脏值丢掉，等于白问一次模型。
 */
export function isAllowedType(field, v, custom) {
  const list = allowedTypes(field, custom);
  const enums = field === 'nature' ? NATURE_LIST : INDUSTRY_LIST;
  const s = String(v == null ? '' : v).trim();
  if (!s) return false;
  if (list.indexOf(s) >= 0) return true;
  const n = typeNorm(s);
  if (!n) return false;
  const hits = list.filter((c) => typeNorm(c) === n);
  if (!hits.length) return false;
  const mine = hits.filter((c) => enums.indexOf(c) < 0);
  if (mine.length === 1) return true;
  return hits.length === 1;
}

/**
 * 把一个自定义值记进本机清单（枚举值不记 —— 它本来就在候选集里）。幂等，上限 40、留最新的。
 * 调用方负责把改过的 data 存回去（saveData），这里只动对象。
 *
 * 记的是"用户用过的值"，与"能不能当模型候选"（customTypesOf 那道收敛）是两件事：
 * 值先记下来，下拉里下次就能选；至于带冒号的那种不适合进提示词的，由 customTypesOf 挡在候选集外。
 */
export function rememberCustomType(data, field, value) {
  const v = String(value == null ? '' : value).trim().slice(0, CUSTOM_MAX_LEN);
  if (!v || isEnumType(field, v)) return false;   // 空值与枚举值不记（这里判的是"是不是枚举"，要逐字）
  if (!data.customTypes || typeof data.customTypes !== 'object') data.customTypes = {};
  const list = Array.isArray(data.customTypes[field]) ? data.customTypes[field] : [];
  if (list.includes(v)) return false;
  data.customTypes[field] = [...list, v].slice(-CUSTOM_MAX_ITEMS);
  return true;
}

/**
 * 这个值是不是「用户自己加的」（在本机清单里、且不是枚举值）—— 决定「删掉这个选项」出不出现。
 * 判据逐字，与 rememberCustomType 同一口径。
 */
export function isCustomType(data, field, value) {
  const v = String(value == null ? '' : value).trim();
  if (!v || isEnumType(field, v)) return false;
  return (data?.customTypes?.[field] || []).some((x) => String(x == null ? '' : x).trim() === v);
}

/**
 * 从本机清单里删掉一个自定义值（内置的 7+14 项删不动 —— 它们是与服务端识别共用的分类体系）。
 * **只动清单，绝不动记录**：记录里存着的那个写法照旧，只是它不再出现在下拉里
 * （要删的值正好是编辑器里选中的那一个时，由 pickers.js 把那一栏清空）。
 * 返回值带上 stillUsed（还有几条记录在用它），界面据此把话说清楚 ——
 * 让用户知道"删的是清单，那些记录要自己去改"，而不是以为删了个假的。
 * 调用方负责把改过的 data 存回去（saveData），这里只动对象。
 * @returns {{removed:boolean, stillUsed:number}}
 */
export function forgetCustomType(data, field, value) {
  const v = String(value == null ? '' : value).trim();
  if (!v || isEnumType(field, v)) return { removed: false, stillUsed: 0 };
  const list = Array.isArray(data?.customTypes?.[field]) ? data.customTypes[field] : [];
  const next = list.filter((x) => String(x == null ? '' : x).trim() !== v);
  const removed = next.length !== list.length;
  if (removed) data.customTypes[field] = next;
  const stillUsed = (data?.records || []).filter((r) => String(r?.[field] ?? '').trim() === v).length;
  return { removed, stillUsed };
}

