// 只剥「股份有限公司」这类法人后缀 —— 「集团」必须留着，
// 否则「上海汽车集团」会变成「上海汽车」，永远匹配不上带集团的别名。
const CORP_SUFFIX = /(股份)?(有限责任|有限公司|公司)$/;

/** 公司名归一化：去空白与不可见字符、去括号注释、去法人后缀。 */
export function normCompanyName(raw) {
  let s = String(raw || '')
    .replace(/[\s\u3000\u200b-\u200f\ufeff]+/g, '')
    .replace(/[（(][^）)]*[）)]/g, '')
    .replace(/[《》「」【】"'`]/g, '');
  for (let i = 0; i < 3; i += 1) {
    const t = s.replace(CORP_SUFFIX, '');
    if (t === s) break;
    s = t;
  }
  return s;
}

/** 生成一个名字的全部比对形态：原名 / 去集团控股 / 各自再剥地名的版本。 */
function forms(norm) {
  const out = [norm];
  const noHold = norm.replace(/(集团|控股|总公司)$/, '');
  if (noHold && noHold !== norm) out.push(noHold);
  for (const f of out.slice()) {
    const r = f.replace(REGION, '');
    if (r && r !== f && r.length >= 2) out.push(r);
  }
  return out;
}

