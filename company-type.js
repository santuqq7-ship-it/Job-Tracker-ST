/**
 * 本地识别：本地库 → 规则。返回 { nature, industry, src }，src 为 'lib' | 'rule' | ''。
 * 两项都为空时 src 为空串，表示「本地认不出来」。
 */
export function guessCompanyType(name) {
  const raw = String(name || '').trim();
  const out = { nature: '', industry: '', src: '' };
  if (!raw) return out;

  const norm = normCompanyName(raw);
  if (!norm) return out;
  const list = forms(norm);

  // ① 本地库：取命中的最长别名
  for (const entry of LIB) {
    if (list.some((f) => f.startsWith(entry.alias))) {
      out.nature = entry.nature;
      out.industry = entry.industry;
      out.src = 'lib';
      return out;
    }
  }

  // ② 关键词规则
  for (const [re, industry] of INDUSTRY_RULES) {
    if (re.test(norm)) {
      out.industry = industry;
      break;
    }
  }
  for (const [re, fn] of NATURE_RULES) {
    if (re.test(norm)) {
      const nature = fn(norm);
      if (nature) {
        out.nature = nature;
        break;
      }
    }
  }
  if (out.nature || out.industry) out.src = 'rule';
  return out;
}

