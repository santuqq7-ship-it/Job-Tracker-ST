/** 把任意写法收敛成枚举值；收敛不了返回 ''（宁可丢，不要脏数据）。 */
export function normalizeTypeValue(field, raw) {
  const v = String(raw == null ? '' : raw).trim().replace(/^["'「」【】\s]+|["'「」【】\s]+$/g, '');
  if (!v) return '';
  const list = field === 'nature' ? NATURE_LIST : INDUSTRY_LIST;
  if (list.indexOf(v) >= 0) return v;
  const table = field === 'nature' ? NATURE_ALIAS : INDUSTRY_ALIAS;
  return table[v] != null ? table[v] : '';
}

/**
 * 表格单元格拆解：把「央企 · 能源/化工」这类混合写法拆成两个字段。
 * 逐段比对枚举，认不出的段落直接丢（不瞎猜）。
 */
export function splitTypeCell(text) {
  const raw = String(text == null ? '' : text).trim();
  const out = { nature: '', industry: '' };
  if (!raw) return out;
  for (const part of raw.split(/[·・•|,，、;；/\s]+/)) {
    const seg = part.trim();
    if (!seg) continue;
    if (!out.nature) {
      const n = normalizeTypeValue('nature', seg);
      // 光一个「其他」分不清是性质还是行业，按行业算（行业那栏是兜底桶）
      if (n && n !== '其他') {
        out.nature = n;
        continue;
      }
    }
    if (!out.industry) {
      const i = normalizeTypeValue('industry', seg);
      if (i) out.industry = i;
    }
  }
  return out;
}

/**
 * 界面上的合并显示：'央企 · 能源/化工'；只填一半就只显示那一半。
 *
 * 这里**不校验枚举**：编辑弹窗允许选「＋ 自定义…」手写一个枚举外的值（'新能源/光伏'），
 * 存进去是它、卡片上就得显示它 —— 显示层再拿枚举卡一遍，用户手填的值会凭空消失。
 * 「是不是枚举值」只在写入口判断（模型回包走 ai.js 的 isValidNature/isValidIndustry）。
 */
export function typeLabel(nature, industry) {
  const n = String(nature == null ? '' : nature).trim();
  const i = String(industry == null ? '' : industry).trim();
  return [n, i].filter(Boolean).join(' · ');
}
